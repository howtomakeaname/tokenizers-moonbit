#!/usr/bin/env python3
"""Generate the BERT `clean_text` control-character range table used by
`is_control` (src/normalizer/normalize_utils.mbt).

HuggingFace `tokenizers` 0.22.2 (`tokenizers/src/normalizers/bert.rs`)
drops every char for which Rust `char::is_other()` is true (Unicode
general categories Cc/Cf/Co/Cs/Cn) except tab, LF and CR, which are
mapped to whitespace instead. U+FFFD is removed as well. The exact set
depends on the Unicode version compiled into the reference library, so
this table is derived EMPIRICALLY from the parity target by sweeping the
full Unicode scalar range (0..=0x10FFFF, surrogates excluded) against
Python `tokenizers` 0.22.2's BertNormalizer. This keeps the port exact
w.r.t. the behavioral-comparison baseline regardless of the local
Python's unicodedata version.

Output: src/normalizer/bert_control_data.mbt
"""
import os

from tokenizers import normalizers

OUT = os.path.join(
    os.path.dirname(__file__), "..", "src", "normalizer", "bert_control_data.mbt"
)

# Matches the BertNormalizer config used by bert-base-uncased-style
# tokenizers: only clean_text matters for the control/whitespace split;
# lowercase and strip_accents are disabled so no other transformation
# interferes with the per-character sweep.
bert = normalizers.BertNormalizer(
    clean_text=True, lowercase=False, strip_accents=False
)


def hf_removes(cp: int) -> bool:
    if 0xD800 <= cp <= 0xDFFF:
        return False
    return bert.normalize_str(chr(cp)) == ""


def main() -> None:
    cps = [cp for cp in range(0x110000) if hf_removes(cp)]
    ranges: list[list[int]] = []
    for cp in cps:
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])

    lines = [
        "// GENERATED by scripts/gen_bert_control.py - codepoints removed by",
        "// BertNormalizer(clean_text=true) in Python `tokenizers` 0.22.2",
        "// (Rust char::is_other, i.e. Unicode Cc/Cf/Co/Cs/Cn, except tab/LF/CR;",
        "// U+FFFD is also removed). Derived from an empirical full-range sweep",
        "// 0..=0x10FFFF; do not edit by hand, regenerate with:",
        "// python3 scripts/gen_bert_control.py",
        "",
        "///|",
        "/// Inclusive [start, stop] codepoint ranges removed by BERT clean_text,",
        "/// sorted ascending. Tab, LF and CR are absent on purpose because BERT",
        "/// maps them to whitespace rather than dropping them.",
        "fn bert_control_ranges() -> Array[(Int32, Int32)] {",
        "  [",
    ]
    for start, stop in ranges:
        lines.append(f"    ({start}, {stop}),")
    lines += [
        "  ]",
        "}",
        "",
    ]

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: {len(cps)} codepoints in {len(ranges)} ranges")


if __name__ == "__main__":
    main()
